//! Resource budgets and margins (Steelbore Standard §22).
//!
//! `doc/budgets.toml` declares each ceiling once, against the requirement that
//! states it, with the resource, the unit and where it is measured: in CI on
//! every build, or on the reference machine (§22.4). `doc/measurements.toml`
//! holds the dated figures. The margin is `(ceiling - measured) / ceiling`,
//! banded as §22.3 says: green above 25 %, amber from 10 % to 25 %, red below
//! 10 %, exceeded below zero.
//!
//! - `cargo xtask budgets [--measured id=value,...] [--release]` prints one
//!   `BUDGET:` line per budget and fails on a red or exceeded margin, which
//!   blocks the release of a Category B project. `--measured` supplies the
//!   figures CI takes on the build it is checking; `--release` also fails a
//!   budget that has never been measured.
//! - `cargo xtask budgets-texi [--check]` writes `doc/budgets.texi`, the table
//!   the manual includes, from the committed files alone, or checks it is
//!   current.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

use serde::{Deserialize, Serialize};

use crate::args::Args;
use crate::paths;
use crate::report::{Envelope, Failure, Finding, print_findings};

/// The budget register, relative to the repository root.
pub const BUDGETS_PATH: &str = "doc/budgets.toml";

/// The measured figures, relative to the repository root.
pub const MEASUREMENTS_PATH: &str = "doc/measurements.toml";

/// The generated table, relative to the repository root.
pub const TEXI_PATH: &str = "doc/budgets.texi";

/// The head of the generated table.
const TEXI_HEADER: &str = "\
@c SPDX-FileCopyrightText: 2026 Mohamed Hammad <Mohamed.Hammad@SpacecraftSoftware.org>
@c SPDX-License-Identifier: CC-BY-SA-4.0
@c GENERATED by `cargo xtask budgets-texi` from doc/budgets.toml and
@c doc/measurements.toml --- do not edit.

";

/// The register: the reference machine and workload, then every ceiling.
#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Register {
    /// Where the reference figures come from.
    pub meta: RegisterMeta,
    /// The ceilings.
    #[serde(default)]
    pub budget: Vec<Budget>,
}

/// The reference machine and workload (§22.4).
#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct RegisterMeta {
    /// CPU, memory, storage and OS of the reference machine.
    pub reference_machine: String,
    /// The fixed, committed workload the figures are taken under.
    pub reference_workload: String,
}

/// Where a budget's figure is taken.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Deserialize, Serialize)]
#[serde(rename_all = "kebab-case")]
pub enum Measured {
    /// In CI, on every build.
    Ci,
    /// On the reference machine, by the maintainer.
    Reference,
}

/// The unit of a ceiling and its figures.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Deserialize, Serialize)]
#[serde(rename_all = "kebab-case")]
pub enum Unit {
    /// Bytes.
    Bytes,
    /// Milliseconds.
    Ms,
}

impl Unit {
    /// `value` in this unit, for people: MiB for bytes, ms for time.
    #[must_use]
    pub fn render(self, value: f64) -> String {
        match self {
            Self::Bytes if value < 1024.0 => format!("{value} B"),
            Self::Bytes if value < 1024.0 * 1024.0 => format!("{:.1} KiB", value / 1024.0),
            Self::Bytes => format!("{:.2} MiB", value / (1024.0 * 1024.0)),
            Self::Ms => format!("{value} ms"),
        }
    }
}

/// One ceiling.
#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Budget {
    /// Stable kebab-case name, e.g. `initrd-binary`.
    pub id: String,
    /// The requirement that states the ceiling.
    pub requirement: String,
    /// The §22.1 resource, e.g. `binary size`.
    pub resource: String,
    /// The ceiling, in `unit`.
    pub ceiling: f64,
    /// The unit of the ceiling and its figures.
    pub unit: Unit,
    /// Where it is measured.
    pub measured: Measured,
    /// How it is measured: the command, the build, the instrument.
    pub method: String,
}

/// The measured figures.
#[derive(Debug, Clone, Default, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Measurements {
    /// One figure per entry; the last entry for a budget is its current one.
    #[serde(default)]
    pub measurement: Vec<Measurement>,
}

/// One dated figure.
#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Measurement {
    /// The budget it measures.
    pub budget: String,
    /// The median, in the budget's unit.
    pub value: f64,
    /// The spread of the runs, in the budget's unit, if more than one ran.
    pub spread: Option<f64>,
    /// `YYYY-MM-DD`.
    pub date: String,
    /// Where it was taken.
    pub machine: String,
    /// Which run or task produced it.
    pub source: String,
}

/// A §22.3 margin band.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "kebab-case")]
pub enum Band {
    /// Above 25 %.
    Green,
    /// 10 % to 25 %.
    Amber,
    /// Below 10 %: blocks the release.
    Red,
    /// Below zero: an anomaly.
    Exceeded,
    /// No figure yet.
    Unmeasured,
}

impl Band {
    /// The band of `margin`, a fraction of the ceiling.
    #[must_use]
    pub fn of(margin: f64) -> Self {
        // A margin that is not a number has not been shown to fit.
        if margin.is_nan() || margin < 0.0 {
            Self::Exceeded
        } else if margin < 0.10 {
            Self::Red
        } else if margin <= 0.25 {
            Self::Amber
        } else {
            Self::Green
        }
    }

    /// Stable lowercase name.
    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Green => "green",
            Self::Amber => "amber",
            Self::Red => "red",
            Self::Exceeded => "exceeded",
            Self::Unmeasured => "unmeasured",
        }
    }

    /// Whether the band blocks a Category B release.
    #[must_use]
    pub const fn blocks(self) -> bool {
        matches!(self, Self::Red | Self::Exceeded)
    }
}

/// A budget with its current figure and margin.
#[derive(Debug, Clone, Serialize)]
pub struct Status {
    /// The budget's id.
    pub id: String,
    /// The requirement that states it.
    pub requirement: String,
    /// The resource.
    pub resource: String,
    /// The ceiling.
    pub ceiling: f64,
    /// The unit.
    pub unit: Unit,
    /// Where it is measured.
    pub measured_on: Measured,
    /// The current figure, if any.
    pub measured: Option<f64>,
    /// Where the figure came from: a date and source, or `this build`.
    pub from: Option<String>,
    /// `(ceiling - measured) / ceiling`.
    pub margin: Option<f64>,
    /// The band.
    pub band: Band,
}

impl Status {
    /// The §22.3 report line, e.g.
    /// `BUDGET: initrd-binary 1.86 MiB / 2.50 MiB (25% margin, amber)`.
    #[must_use]
    pub fn line(&self) -> String {
        match (self.measured, self.margin) {
            (Some(measured), Some(margin)) => format!(
                "BUDGET: {} {} / {} ({} margin, {})",
                self.id,
                self.unit.render(measured),
                self.unit.render(self.ceiling),
                percent(margin),
                self.band.as_str()
            ),
            _ => format!(
                "BUDGET: {} unmeasured / {} ({})",
                self.id,
                self.unit.render(self.ceiling),
                match self.measured_on {
                    Measured::Ci => "measured in CI",
                    Measured::Reference => "measured on the reference machine",
                }
            ),
        }
    }
}

/// Checks the register against the requirement set and the figures against
/// the register.
#[must_use]
pub fn validate(
    register: &Register,
    measurements: &Measurements,
    requirements: &[String],
) -> Vec<Finding> {
    let mut findings = Vec::new();
    let mut seen = std::collections::BTreeSet::new();
    for budget in &register.budget {
        if !seen.insert(budget.id.as_str()) {
            findings.push(Finding::new(
                "DUPLICATE_BUDGET",
                Some(&budget.requirement),
                format!("budget `{}` is declared twice", budget.id),
            ));
        }
        if !requirements.contains(&budget.requirement) {
            findings.push(Finding::new(
                "UNKNOWN_REQUIREMENT",
                Some(&budget.requirement),
                format!("budget `{}` cites a requirement not in the set", budget.id),
            ));
        }
        if !(budget.ceiling.is_finite() && budget.ceiling > 0.0) {
            findings.push(Finding::new(
                "BAD_CEILING",
                Some(&budget.requirement),
                format!("budget `{}` has no positive ceiling", budget.id),
            ));
        }
    }
    for measurement in &measurements.measurement {
        if !seen.contains(measurement.budget.as_str()) {
            findings.push(Finding::new(
                "UNKNOWN_BUDGET",
                None,
                format!(
                    "a measurement of {} cites budget `{}`, which is not declared",
                    measurement.date, measurement.budget
                ),
            ));
        }
        if !(measurement.value.is_finite() && measurement.value >= 0.0) {
            findings.push(Finding::new(
                "BAD_MEASUREMENT",
                None,
                format!(
                    "the measurement of `{}` is not a figure",
                    measurement.budget
                ),
            ));
        }
    }
    findings
}

/// Every budget with its current figure: an override from `this_build`, else
/// the last entry in `measurements`.
#[must_use]
pub fn status(
    register: &Register,
    measurements: &Measurements,
    this_build: &BTreeMap<String, f64>,
) -> Vec<Status> {
    register
        .budget
        .iter()
        .map(|budget| {
            let recorded = measurements
                .measurement
                .iter()
                .rev()
                .find(|m| m.budget == budget.id)
                .map(|m| (m.value, format!("{} ({})", m.date, m.source)));
            let current = this_build
                .get(&budget.id)
                .map(|&value| (value, "this build".to_owned()))
                .or(recorded);
            let (measured, from) = current.map_or((None, None), |(v, f)| (Some(v), Some(f)));
            let margin = measured.map(|m| (budget.ceiling - m) / budget.ceiling);
            Status {
                id: budget.id.clone(),
                requirement: budget.requirement.clone(),
                resource: budget.resource.clone(),
                ceiling: budget.ceiling,
                unit: budget.unit,
                measured_on: budget.measured,
                measured,
                from,
                margin,
                band: margin.map_or(Band::Unmeasured, Band::of),
            }
        })
        .collect()
}

/// Parses `id=value,id=value`.
///
/// # Errors
///
/// A usage failure for a pair that is not `id=number`.
pub fn parse_overrides(text: &str) -> Result<BTreeMap<String, f64>, Failure> {
    let mut map = BTreeMap::new();
    for pair in text.split(',').filter(|p| !p.trim().is_empty()) {
        let (id, value) = pair
            .split_once('=')
            .and_then(|(id, value)| Some((id.trim(), value.trim().parse::<f64>().ok()?)))
            .filter(|(_, value)| value.is_finite() && *value >= 0.0)
            .ok_or_else(|| {
                Failure::usage(
                    format!("`{pair}` is not `budget=value` with a finite, non-negative value"),
                    "cargo xtask budgets --measured initrd-binary=1954776",
                )
            })?;
        map.insert(id.to_owned(), value);
    }
    Ok(map)
}

/// Loads the register and the figures under `root`.
///
/// # Errors
///
/// A missing or malformed register; a malformed measurements file. A missing
/// measurements file is no figures.
pub fn load(root: &Path) -> Result<(Register, Measurements), Failure> {
    let register: Register = toml::from_str(&paths::read_text(
        &root.join(BUDGETS_PATH),
        "cargo xtask budgets",
    )?)?;
    let measurements_path = root.join(MEASUREMENTS_PATH);
    let measurements = if measurements_path.exists() {
        toml::from_str(&paths::read_text(
            &measurements_path,
            "cargo xtask budgets",
        )?)?
    } else {
        Measurements::default()
    };
    Ok((register, measurements))
}

fn checked(root: &Path) -> Result<(Register, Measurements), Failure> {
    let (register, measurements) = load(root)?;
    let set = crate::requirements::load(&root.join(crate::requirements::DEFAULT_PATH))?;
    let ids: Vec<String> = set.requirement.iter().map(|r| r.id.clone()).collect();
    let findings = validate(&register, &measurements, &ids);
    if !findings.is_empty() {
        print_findings("ERROR", &findings);
        return Err(Failure::gate(
            format!("the budget register has {} error(s)", findings.len()),
            "cargo xtask budgets",
        ));
    }
    Ok((register, measurements))
}

#[derive(Debug, Serialize)]
struct Output {
    release: bool,
    budgets: Vec<Status>,
}

/// `cargo xtask budgets`.
///
/// # Errors
///
/// A malformed register, a red or exceeded margin, or under `--release` an
/// unmeasured budget.
pub fn run(args: &Args) -> Result<(), Failure> {
    args.ensure_known(&["measured", "release"])?;
    let root = args.root();
    let (register, measurements) = checked(&root)?;
    let overrides = args
        .value("measured")
        .map_or_else(|| Ok(BTreeMap::new()), parse_overrides)?;
    if let Some(unknown) = overrides
        .keys()
        .find(|id| !register.budget.iter().any(|b| &b.id == *id))
    {
        return Err(Failure::usage(
            format!("`--measured` names budget `{unknown}`, which is not declared"),
            "cargo xtask budgets",
        ));
    }
    let release = args.flag("release");
    let budgets = status(&register, &measurements, &overrides);
    let blocking: Vec<&Status> = budgets
        .iter()
        .filter(|s| s.band.blocks() || (release && s.band == Band::Unmeasured))
        .collect();
    let blocked: Vec<String> = blocking.iter().map(|s| s.id.clone()).collect();
    if args.json() {
        Envelope::new(&args.command_line(), Output { release, budgets }).print()?;
    } else {
        for budget in &budgets {
            let tag = match budget.band {
                Band::Green => "[OK]",
                Band::Amber | Band::Unmeasured => "[WARN]",
                Band::Red | Band::Exceeded => "[ERROR]",
            };
            println!("{tag} {}", budget.line());
        }
    }
    if blocked.is_empty() {
        Ok(())
    } else {
        Err(Failure::gate(
            format!("budget(s) block the release: {}", blocked.join(", ")),
            "cargo xtask budgets --json",
        ))
    }
}

/// The Texinfo table of every budget, from the committed files alone.
#[must_use]
pub fn render_texi(register: &Register, measurements: &Measurements) -> String {
    let mut out = String::new();
    out.push_str(TEXI_HEADER);
    let _ = writeln!(
        out,
        "Reference machine: {}\n\nReference workload: {}\n",
        texi_escape(&register.meta.reference_machine),
        texi_escape(&register.meta.reference_workload)
    );
    out.push_str("@multitable @columnfractions .2 .16 .16 .16 .14 .18\n");
    out.push_str(
        "@headitem Budget @tab Requirement @tab Ceiling @tab Measured @tab Margin @tab Band\n",
    );
    for s in status(register, measurements, &BTreeMap::new()) {
        let measured = s
            .measured
            .map_or_else(|| "---".to_owned(), |m| s.unit.render(m));
        let margin = s.margin.map_or_else(|| "---".to_owned(), percent);
        let _ = writeln!(
            out,
            "@item {} @tab {} @tab {} @tab {} @tab {} @tab {}",
            texi_escape(&s.id),
            s.requirement,
            s.unit.render(s.ceiling),
            measured,
            texi_escape(&margin),
            s.band.as_str()
        );
    }
    out.push_str("@end multitable\n\n@table @code\n");
    for budget in &register.budget {
        let _ = writeln!(
            out,
            "@item {}\n{} ({}). {}",
            texi_escape(&budget.id),
            texi_escape(&budget.resource),
            match budget.measured {
                Measured::Ci => "measured in CI on every build",
                Measured::Reference => "measured on the reference machine",
            },
            texi_escape(&budget.method)
        );
    }
    out.push_str("@end table\n");
    out
}

/// A margin as a percentage, cut (never rounded) to one decimal, so a figure
/// just inside a band never reads as the band's edge.
fn percent(margin: f64) -> String {
    format!("{:.1}%", (margin * 1000.0).floor() / 10.0)
}

/// Escapes Texinfo's special characters.
fn texi_escape(text: &str) -> String {
    text.replace('@', "@@")
        .replace('{', "@{")
        .replace('}', "@}")
}

/// `cargo xtask budgets-texi [--check]`.
///
/// # Errors
///
/// A malformed register, or under `--check` a stale `doc/budgets.texi`.
pub fn run_texi(args: &Args) -> Result<(), Failure> {
    args.ensure_known(&["check"])?;
    let root = args.root();
    let (register, measurements) = checked(&root)?;
    let content = render_texi(&register, &measurements);
    let path = root.join(TEXI_PATH);
    if args.flag("check") {
        let current = std::fs::read(&path).is_ok_and(|bytes| bytes == content.as_bytes());
        if !current {
            return Err(Failure::gate(
                format!("`{TEXI_PATH}` is out of date"),
                "cargo xtask budgets-texi",
            ));
        }
        println!("[OK] {TEXI_PATH} current");
    } else {
        std::fs::write(&path, content)?;
        println!("[OK] {TEXI_PATH} written");
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn register() -> Register {
        toml::from_str(
            r#"
            [meta]
            reference_machine = "T490s"
            reference_workload = "cold boot"
            [[budget]]
            id = "binary"
            requirement = "FRN-SRS-105"
            resource = "binary size"
            ceiling = 1000.0
            unit = "bytes"
            measured = "ci"
            method = "stat"
            [[budget]]
            id = "first-frame"
            requirement = "FRN-SRS-004"
            resource = "cold-start latency"
            ceiling = 150.0
            unit = "ms"
            measured = "reference"
            method = "presenter stats"
            "#,
        )
        .unwrap_or_else(|e| panic!("{e}"))
    }

    #[test]
    fn margins_fall_in_the_section_22_3_bands() {
        assert_eq!(Band::of(0.5), Band::Green);
        assert_eq!(Band::of(0.25), Band::Amber);
        assert_eq!(Band::of(0.10), Band::Amber);
        assert_eq!(Band::of(0.099), Band::Red);
        assert_eq!(Band::of(-0.01), Band::Exceeded);
        assert!(Band::Red.blocks() && Band::Exceeded.blocks());
        assert!(!Band::Amber.blocks() && !Band::Unmeasured.blocks());
    }

    #[test]
    fn the_latest_figure_counts_and_this_build_overrides_it() {
        let register = register();
        let measurements: Measurements = toml::from_str(
            r#"
            [[measurement]]
            budget = "first-frame"
            value = 40.0
            date = "2026-10-01"
            machine = "T490s"
            source = "old"
            [[measurement]]
            budget = "first-frame"
            value = 20.5
            spread = 1.2
            date = "2026-10-14"
            machine = "T490s"
            source = "T-029"
            "#,
        )
        .unwrap_or_else(|e| panic!("{e}"));
        let overrides = parse_overrides("binary=950").unwrap_or_else(|e| panic!("{e}"));
        let status = status(&register, &measurements, &overrides);
        assert_eq!(status[0].band, Band::Red);
        assert_eq!(
            status[0].line(),
            "BUDGET: binary 950 B / 1000 B (5.0% margin, red)"
        );
        assert_eq!(status[1].measured, Some(20.5));
        assert_eq!(status[1].band, Band::Green);
        assert_eq!(
            status[1].line(),
            "BUDGET: first-frame 20.5 ms / 150 ms (86.3% margin, green)"
        );
        let unmeasured = super::status(&register, &Measurements::default(), &BTreeMap::new());
        assert_eq!(unmeasured[0].band, Band::Unmeasured);
        assert!(unmeasured[0].line().contains("unmeasured"));
    }

    #[test]
    fn the_register_cites_known_requirements_and_measures_known_budgets() {
        let register = register();
        let measurements: Measurements = toml::from_str(
            r#"
            [[measurement]]
            budget = "nonexistent"
            value = 1.0
            date = "2026-10-14"
            machine = "T490s"
            source = "x"
            "#,
        )
        .unwrap_or_else(|e| panic!("{e}"));
        let findings = validate(&register, &measurements, &["FRN-SRS-004".to_owned()]);
        let codes: Vec<&str> = findings.iter().map(|f| f.code.as_str()).collect();
        assert_eq!(codes, ["UNKNOWN_REQUIREMENT", "UNKNOWN_BUDGET"]);
        assert!(parse_overrides("a=1,b=x").is_err());
        assert!(parse_overrides("a=NaN").is_err());
        assert!(parse_overrides("a=-1").is_err());
        assert!(parse_overrides("a=inf").is_err());
        assert_eq!(Band::of(f64::NAN), Band::Exceeded);
        assert_eq!(parse_overrides("").map(|m| m.len()).ok(), Some(0));
    }

    #[test]
    fn the_committed_register_is_valid_and_its_table_current() {
        let root = crate::paths::default_root();
        let (register, measurements) = load(&root).unwrap_or_else(|e| panic!("{e}"));
        let set = crate::requirements::load(&root.join(crate::requirements::DEFAULT_PATH))
            .unwrap_or_else(|e| panic!("{e}"));
        let ids: Vec<String> = set.requirement.iter().map(|r| r.id.clone()).collect();
        assert_eq!(validate(&register, &measurements, &ids), Vec::new());
        let texi = std::fs::read_to_string(root.join(TEXI_PATH)).unwrap_or_default();
        assert_eq!(
            texi,
            render_texi(&register, &measurements),
            "run `cargo xtask budgets-texi`"
        );
    }
}
